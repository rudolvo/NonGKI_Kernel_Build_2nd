# ---------- 字体设置辅助函数 ----------
def set_font(run, name, size, bold=False):
    """设置run的字体、字号、加粗，并正确设置中文字体"""
    run.font.name = name
    run._element.rPr.rFonts.set(qn('w:eastAsia'), name)
    run.font.size = Pt(size)
    run.font.bold = bold

def add_para(doc, text, font_name='宋体', font_size=10.5, bold=False,
             align=None, first_line_indent=None, space_after=0, space_before=0):
    """添加一个段落并设置格式"""
    p = doc.add_paragraph()
    if align is not None:
        p.alignment = align
    if first_line_indent is not None:
        p.paragraph_format.first_line_indent = Pt(first_line_indent)
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.space_before = Pt(space_before)
    run = p.add_run(text)
    set_font(run, font_name, font_size, bold)
    return p

def add_empty_line(doc, size=10.5):
    """添加空行（空段落）"""
    p = doc.add_paragraph()
    run = p.add_run('')
    set_font(run, '宋体', size)
    return p

