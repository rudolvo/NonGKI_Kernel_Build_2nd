# ---------- 工具函数 ----------
def set_font(run, font_name, size, bold=False):
    """设置中英文字体、字号、加粗"""
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.name = font_name
    rPr = run._element.get_or_add_rPr()
    rFonts = rPr.find(qn('w:rFonts'))
    if rFonts is None:
        rFonts = OxmlElement('w:rFonts')
        rPr.append(rFonts)
    rFonts.set(qn('w:eastAsia'), font_name)
    rFonts.set(qn('w:ascii'), font_name)
    rFonts.set(qn('w:hAnsi'), font_name)

def add_empty():
    doc.add_paragraph()

def add_title(text):
    """题目：三号宋体，加粗，居中"""
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run(text)
    set_font(run, '宋体', 16, True)  # 三号=16pt

def add_author(text):
    """作者姓名：小四号宋体，居中"""
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run(text)
    set_font(run, '宋体', 12)  # 小四=12pt

def add_unit(text):
    """单位全称：五号楷体，居中"""
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run(text)
    set_font(run, '楷体', 10.5)  # 五号=10.5pt

def add_abstract(text):
    """摘要：小五号仿宋体，'摘要'用小五号宋体"""
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    run1 = p.add_run('【摘要】')
    set_font(run1, '宋体', 9)  # 小五=9pt
    run2 = p.add_run(text)
    set_font(run2, '仿宋', 9)

def add_keywords(text):
    """关键词：小五号仿宋体，'关键词'用小五号宋体"""
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    run1 = p.add_run('【关键词】')
    set_font(run1, '宋体', 9)
    run2 = p.add_run(text)
    set_font(run2, '仿宋', 9)

def add_h1(text):
    """一级标题：小四号宋体加粗，独占一行，末尾不加标点"""
    p = doc.add_paragraph()
    run = p.add_run(text)
    set_font(run, '宋体', 12, True)  # 小四=12pt

def add_h2(text):
    """二级标题：五号宋体加粗，独占一行，末尾不加标点"""
    p = doc.add_paragraph()
    run = p.add_run(text)
    set_font(run, '宋体', 10.5, True)  # 五号=10.5pt

def add_body(text):
    """正文：五号宋体，每段起首空两格，回行顶格"""
    p = doc.add_paragraph()
    p.paragraph_format.first_line_indent = Pt(21)  # 2字符≈21pt
    run = p.add_run(text)
    set_font(run, '宋体', 10.5)

def add_ref_title(text):
    """参考文献标题：五号黑体，顶格居左，独占1行"""
    p = doc.add_paragraph()
    run = p.add_run(text)
    set_font(run, '黑体', 10.5)

def add_ref(text):
    """参考文献内容：小五号仿宋体，顶格排列"""
    p = doc.add_paragraph()
    run = p.add_run(text)
    set_font(run, '仿宋', 9)

